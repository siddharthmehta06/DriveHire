const PDFDocument = require('pdfkit');

function generateReceiptPdf(payment) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const buffers = [];

      doc.on('data', (chunk) => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', reject);

      // Header
      doc.fontSize(22).font('Helvetica-Bold').text('DriveHire Digital Receipt', { align: 'center' });
      doc.moveDown(0.5);
      doc.fontSize(10).font('Helvetica').text('Official Electronic Payment Record', { align: 'center' });
      doc.moveDown(1.5);

      // Receipt Metadata
      doc.fontSize(11).font('Helvetica-Bold').text('Receipt Details');
      doc.font('Helvetica');
      doc.text(`Receipt Number: ${payment.receiptNumber || 'N/A'}`);
      doc.text(`Issue Date (UTC): ${payment.paidAt ? new Date(payment.paidAt).toISOString() : new Date().toISOString()}`);
      doc.text(`Payment Status: ${payment.status}`);
      doc.text(`Payment Method: ${payment.method || 'N/A'}`);
      doc.moveDown(1);

      // Participant Metadata
      doc.font('Helvetica-Bold').text('Transaction Participants');
      doc.font('Helvetica');
      doc.text(`Payer: ${payment.payer?.name || payment.payerId} <${payment.payer?.email || 'N/A'}>`);
      doc.text(`Payee: ${payment.payee?.name || payment.payeeId} <${payment.payee?.email || 'N/A'}>`);
      doc.text(`Booking Reference: ${payment.bookingId}`);
      if (payment.booking?.type) {
        doc.text(`Booking Type: ${payment.booking.type}`);
      }
      doc.moveDown(1);

      // Financial Breakdown
      doc.font('Helvetica-Bold').text('Fare & Fee Breakdown');
      doc.font('Helvetica');
      doc.text(`Base Amount: INR ${Number(payment.baseAmount).toFixed(2)}`);

      if (Number(payment.discountAmount) > 0) {
        const promoLabel = payment.promoCode?.code ? ` (${payment.promoCode.code})` : '';
        doc.text(`Promo Discount${promoLabel}: -INR ${Number(payment.discountAmount).toFixed(2)}`);
      }

      doc.font('Helvetica-Bold');
      doc.text(`Total Payable: INR ${Number(payment.amount).toFixed(2)}`);
      doc.font('Helvetica');
      doc.text(`Platform Commission: INR ${Number(payment.commissionAmount).toFixed(2)} (${Number(payment.commissionRatePct).toFixed(2)}%)`);
      doc.text(`Net Payee Disbursal: INR ${Number(payment.payeeAmount).toFixed(2)}`);
      doc.moveDown(2);

      // Footer
      doc.fontSize(9).fillColor('#666666').text(
        'Generated by DriveHire Platform. This is a computer-generated receipt and requires no physical signature.',
        { align: 'center' }
      );

      doc.end();
    } catch (err) {
      reject(err);
    }
  });
}

module.exports = { generateReceiptPdf };
